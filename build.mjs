function llmsFull() {
  const parts = [
    `# Ben Velazquez — full site text`,
    ``,
    `Source: ${site.origin}`,
    `Generated: ${BUILD_DATE}`,
    `Licence: content © ${new Date().getFullYear()} Ben Velazquez. Quotation with attribution to ${site.origin} is welcome.`,
    ``,
  ];

  for (const route of routes) {
    const page = contentEn[route.key];
    if (!page) continue;
    parts.push(`\n---\n`);
    parts.push(`## ${page.seo.title}`);
    parts.push(`URL: ${urlFor(route.key, 'en')}`);
    parts.push(`Description: ${page.seo.description}`);
    parts.push('');
    if (page.hero) parts.push(`${plain(page.hero.h1)}. ${plain(page.hero.lede || '')}`);
    if (page.answer) {
      parts.push('');
      parts.push('### Summary');
      page.answer.forEach((p) => parts.push(plain(p)));
    }
    if (page.facts) {
      parts.push('');
      parts.push('### At a glance');
      page.facts.forEach((f) => parts.push(`- ${f.k}: ${plain(f.v)}`));
    }
    const faqs = collectFaqs(page);
    if (faqs) {
      parts.push('');
      parts.push('### FAQ');
      faqs.forEach((f) => {
        parts.push(`Q: ${plain(f.q)}`);
        parts.push(`A: ${plain(f.a)}`);
        parts.push('');
      });
    }
  }

  parts.push(`\n---\n`);
  parts.push(`## Insights`);
  for (const post of insights) {
    parts.push('');
    parts.push(`### ${post.title.en}`);
    parts.push(`URL: ${urlFor('insights', 'en')}${post.slug.en}/`);
    parts.push(`Published: ${post.date} · Topic: ${post.tag.en}`);
    parts.push('');
    post.answer.en.forEach((p) => parts.push(plain(p)));
    parts.push('');
    parts.push(plain(post.body.en));
    parts.push('');
    post.faqs.en.forEach((f) => {
      parts.push(`Q: ${plain(f.q)}`);
      parts.push(`A: ${plain(f.a)}`);
    });
  }

  return parts.join('\n');
}

write('llms.txt', llmsIndex());
write('llms-full.txt', llmsFull());

