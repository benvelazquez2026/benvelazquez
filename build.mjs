function feed(locale) {
  const t = ui[locale];
  const self = locale === 'en' ? '/feed.xml' : '/es/feed.xml';
  const items = insights
    .map((post) => {
      const url = `${urlFor('insights', locale)}${post.slug[locale]}/`;
      return `<item>
<title>${esc(post.title[locale])}</title>
<link>${esc(url)}</link>
<guid isPermaLink="true">${esc(url)}</guid>
<pubDate>${new Date(`${post.date}T12:00:00Z`).toUTCString()}</pubDate>
<category>${esc(post.tag[locale])}</category>
<description>${esc(post.summary[locale])}</description>
<content:encoded><![CDATA[${post.body[locale]}]]></content:encoded>
</item>`;
    })
    .join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:content="http://purl.org/rss/1.0/modules/content/">
<channel>
<title>${esc(t.rssTitle)}</title>
<link>${esc(urlFor('insights', locale))}</link>
<atom:link href="${esc(absolute(self))}" rel="self" type="application/rss+xml"/>
<description>${esc(contentEn.insights.seo.description)}</description>
<language>${locale === 'es' ? 'es' : 'en-us'}</language>
<lastBuildDate>${new Date().toUTCString()}</lastBuildDate>
<copyright>© ${new Date().getFullYear()} ${esc(site.name)}</copyright>
${items}
</channel>
</rss>
`;
}

write('feed.xml', feed('en'));
