function sitemapEntry(url, alternates, priority, changefreq, lastmod) {
  const links = alternates
    .map((a) => `<xhtml:link rel="alternate" hreflang="${a.locale}" href="${esc(a.url)}"/>`)
    .join('');
  const xDefault = alternates.find((a) => a.locale === site.defaultLocale);
  return `<url><loc>${esc(url)}</loc>${
    lastmod ? `<lastmod>${lastmod}</lastmod>` : ''
  }<changefreq>${changefreq}</changefreq><priority>${priority}</priority>${links}${
    xDefault ? `<xhtml:link rel="alternate" hreflang="x-default" href="${esc(xDefault.url)}"/>` : ''
  }</url>`;
}

const sitemapUrls = [];
const today = BUILD_DATE.slice(0, 10);

for (const route of routes) {
  if (!contentEn[route.key]) continue;
  const alternates = site.locales.map((l) => ({ locale: l, url: urlFor(route.key, l) }));
  for (const locale of site.locales) {
    sitemapUrls.push(sitemapEntry(urlFor(route.key, locale), alternates, route.priority, route.changefreq, today));
  }
}

for (const post of insights) {
  const alternates = site.locales.map((l) => ({
    locale: l,
    url: `${urlFor('insights', l)}${post.slug[l]}/`,
  }));
  for (const locale of site.locales) {
    sitemapUrls.push(
      sitemapEntry(`${urlFor('insights', locale)}${post.slug[locale]}/`, alternates, 0.7, 'yearly', post.updated),
    );
  }
}

write(
  'sitemap.xml',
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${sitemapUrls.join('\n')}
</urlset>
`,
);

