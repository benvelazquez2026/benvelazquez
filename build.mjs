#!/usr/bin/env node
/**
 * benvelazquez.com — static site build.
 *
 * Zero dependencies. Reads content from src/data, renders every page in
 * every locale through the shared layout (which guarantees the SEO head),
 * and writes a fully static dist/ that Cloudflare Workers serves directly.
 *
 *   npm run build
 */

import { mkdirSync, writeFileSync, rmSync, cpSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { site, routes, pathFor, urlFor, absolute } from './src/data/site.js';
import { ui } from './src/data/ui.js';
import { insights } from './src/data/insights.js';
import { content as contentEn, credentialsCopy as credsEn } from './src/data/content.en.js';
import { content as contentEs, credentialsCopy as credsEs } from './src/data/content.es.js';
import { renderPage } from './src/lib/layout.js';
import { esc, plain, clamp } from './src/lib/html.js';
import {
  personEntity,
  businessEntity,
  websiteEntity,
  webPageEntity,
  breadcrumbEntity,
  faqEntity,
} from './src/lib/schema.js';
import * as pages from './src/pages/index.js';

const ROOT = dirname(fileURLToPath(import.meta.url));
const DIST = join(ROOT, 'dist');
const PUBLIC = join(ROOT, 'public');

const LOCALE_DATA = {
  en: { content: contentEn, creds: credsEn },
  es: { content: contentEs, creds: credsEs },
};

const BUILD_DATE = new Date().toISOString();
const written = [];

/* ------------------------------------------------------------------ */
/* Helpers                                                             */
/* ------------------------------------------------------------------ */

function write(relPath, body) {
  const full = join(DIST, relPath);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, body);
  written.push({ path: relPath, bytes: Buffer.byteLength(body) });
}

/** Write an HTML page at a directory path so the URL ends in a slash. */
function writePage(urlPath, html) {
  const rel = urlPath === '/' ? 'index.html' : `${urlPath.replace(/^\/|\/$/g, '')}/index.html`;
  write(rel, html);
}

/** Collect FAQs from a page whether they are flat or grouped. */
function collectFaqs(page) {
  if (page.faqs) return page.faqs;
  if (page.groups) return page.groups.flatMap((g) => g.faqs);
  return null;
}

/**
 * Per-page Open Graph image, generated by `npm run og`. Falls back to the
 * default card if a page-specific one has not been rendered yet, so the
 * build never emits a broken social preview.
 */
function ogFor(name) {
  const file = `/img/og-${name}.jpg`;
  return absolute(existsSync(join(PUBLIC, file)) ? file : '/img/og-default.jpg');
}

/**
 * Render one page: merge the page-specific output with the site-wide
 * schema graph and hand it to the layout. Everything funnels through
 * here, which is why no page can ship without canonical/hreflang/JSON-LD.
 */
function emit({ locale, key, urlPath, seo, built, extra = {}, alternates }) {
  const url = absolute(urlPath);
  const faqs = extra.faqs;

  const schema = [
    personEntity(locale),
    businessEntity(locale),
    websiteEntity(locale),
    webPageEntity({
      url,
      title: seo.title,
      description: clamp(seo.description),
      locale,
      breadcrumb: built.breadcrumb && built.breadcrumb.length > 1,
      datePublished: extra.datePublished,
      dateModified: extra.dateModified,
      type: extra.pageType,
    }),
    built.breadcrumb && built.breadcrumb.length > 1 ? breadcrumbEntity(url, built.breadcrumb) : null,
    faqs && faqs.length ? faqEntity(url, faqs) : null,
    ...built.schema,
  ];

  const html = renderPage({
    locale,
    key,
    url,
    title: seo.title,
    description: seo.description,
    content: built.html,
    schema,
    breadcrumb: built.breadcrumb,
    alternates,
    noindex: extra.noindex,
    ogType: extra.ogType,
    ogImage: extra.ogImage,
    publishedTime: extra.datePublished,
    modifiedTime: extra.dateModified,
  });

  writePage(urlPath, html);
  return { url, urlPath, key, locale, seo };
}

/* ------------------------------------------------------------------ */
/* Build                                                               */
/* ------------------------------------------------------------------ */

console.log('→ Cleaning dist/');
rmSync(DIST, { recursive: true, force: true });
mkdirSync(DIST, { recursive: true });

if (existsSync(PUBLIC)) {
  console.log('→ Copying static assets');
  cpSync(PUBLIC, DIST, { recursive: true });
}

const emitted = [];

for (const locale of site.locales) {
  const { content, creds } = LOCALE_DATA[locale];

  for (const route of routes) {
    const key = route.key;
    const page = content[key];
    if (!page) continue;

    const urlPath = pathFor(key, locale);
    let built;

    switch (key) {
      case 'home':
        built = pages.buildHome({ locale, content, credentialsCopy: creds });
        break;
      case 'method':
        built = pages.buildMethod({ locale, page });
        break;
      case 'about':
        built = pages.buildAbout({ locale, page, credentialsCopy: creds });
        break;
      case 'programs':
        built = pages.buildPrograms({ locale, page, content });
        break;
      case 'results':
        built = pages.buildResults({ locale, page });
        break;
      case 'insights':
        built = pages.buildInsightsIndex({ locale, page });
        break;
      case 'faq':
        built = pages.buildFaq({ locale, page });
        break;
      case 'apply':
        built = pages.buildApply({ locale, page });
        break;
      case 'contact':
        built = pages.buildContact({ locale, page });
        break;
      case 'podcast':
        built = pages.buildPodcast({ locale, page });
        break;
      case 'whatIUse':
        built = pages.buildWhatIUse({ locale, page });
        break;
      case 'privacy':
      case 'terms':
      case 'disclosure':
        built = pages.buildLegal({ locale, key, page });
        break;
      default:
        built = pages.buildStandardPage({ locale, key, page, content });
    }

    emitted.push(
      emit({
        locale,
        key,
        urlPath,
        seo: page.seo,
        built,
        extra: { faqs: collectFaqs(page), ogImage: ogFor(`${key}-${locale}`) },
      }),
    );
  }

  /* ---- Insight articles ---- */
  for (const post of insights) {
    const urlPath = `${pathFor('insights', locale)}${post.slug[locale]}/`;
    const built = pages.buildInsightPost({ locale, post, page: content.insights });
    const alternates = site.locales.map((l) => ({
      locale: l,
      url: `${urlFor('insights', l)}${post.slug[l]}/`,
    }));

    emitted.push(
      emit({
        locale,
        key: 'insights',
        urlPath,
        seo: { title: `${post.title[locale]} | ${site.name}`, description: post.meta[locale] },
        built,
        alternates,
        extra: {
          faqs: post.faqs[locale],
          datePublished: post.date,
          dateModified: post.updated,
          ogType: 'article',
          pageType: 'WebPage',
          ogImage: ogFor(`insight-${post.slug[locale]}`),
        },
      }),
    );
  }

  /* ---- 404 ---- */
  const nf = content.notFound;
  const nfBuilt = pages.buildNotFound({ locale, page: nf });
  const nfUrl = absolute(locale === 'en' ? '/404.html' : '/es/404.html');
  const nfHtml = renderPage({
    locale,
    key: 'home',
    url: nfUrl,
    title: nf.seo.title,
    description: nf.seo.description,
    content: nfBuilt.html,
    schema: [
      personEntity(locale),
      businessEntity(locale),
      websiteEntity(locale),
      webPageEntity({
        url: nfUrl,
        title: nf.seo.title,
        description: nf.seo.description,
        locale,
      }),
    ],
    breadcrumb: [],
    noindex: true,
  });
  write(locale === 'en' ? '404.html' : 'es/404.html', nfHtml);
}

console.log(`→ Rendered ${emitted.length} pages`);

